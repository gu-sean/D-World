// 러닝 미션을 다른 운동으로 바꿀 수 있는지 (날씨·일정 때문에 못 뛸 때)
//
// 최종 목표가 러닝 자체이면("10km 뛰기" 등) 다른 운동으로 바꿔도 목표에 도움이 안 되므로 날짜만 옮기게 한다.
// "건강해지기"·"체력 키우기"처럼 운동 종류가 정해지지 않은 목표는 실내 운동으로 바꿔도 도움이 된다.
// 목표에는 운동 종류 칸이 없어서(DB를 바꾸지 않는다) 제목의 러닝 관련 낱말로 판단한다.
// 이 판단은 화면 안내용이다. 미션을 취소하고 새로 만드는 것은 사용자가 직접 해도 되는 일이라 서버가 막지 않는다.
const RUNNING_GOAL_WORDS = /러닝|런닝|달리기|조깅|마라톤|뛰기|뛰어|km|킬로/i;

/** 목표 제목이 러닝 자체를 목표로 하는지. 목표가 없는 미션(null)은 바꿀 수 있다. */
export function isRunningGoal(goalTitle) {
  return RUNNING_GOAL_WORDS.test(goalTitle ?? '');
}

export default { isRunningGoal };
